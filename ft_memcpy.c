#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t nbyte)
{
	unsigned char		*d;
	const unsigned char	*s;
	size_t				i;

	d = (unsigned char *) dest;
	s = (const unsigned char *) src;
	i = 0;
	while (i < nbyte)
	{
		d[i] = s[i];
		i++;
	}
	return (dest);
}
